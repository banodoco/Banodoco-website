import assert from 'node:assert/strict';
import { createHeroGroundDimClaim, createHeroGroundDepartureHold } from '../journey/chapters/hero-ground-dim.js';
const uniform = { value: 1 };
const scene = { groups: { ground: { children: [{ visible: true, material: { uniforms: { uWin: {}, uOpacity: uniform } } }] } } };
const options = { keeps: [0.1] };
const field = createHeroGroundDimClaim(scene, options);
const flight = createHeroGroundDepartureHold(scene, options);
field.set(1);
flight.setFlight(true, 1);
field.clear();
for (let n = 0; n < 180; n++) flight.step(1 / 60);
assert.ok(Math.abs(uniform.value - 0.1) < 1e-9, 'ground stays dim after field retires, throughout flight');
flight.setFlight(false, 0);
assert.ok(Math.abs(uniform.value - 0.1) < 1e-9, 'landing/retarget does not brighten a frame');
flight.step(0.5);
const interrupted = uniform.value;
assert.ok(interrupted > 0.1 && interrupted < 1, 'release is gradual');
flight.setFlight(true, 0);
flight.step(1);
assert.equal(uniform.value, interrupted, 'retarget into Equip carries the current dim without a reset');
flight.setFlight(false, 0);
field.set(0.5);
flight.step(1.5);
assert.equal(uniform.value, 0.55, 'releasing flight preserves another chapter claim');
field.clear();
assert.equal(uniform.value, 1, 'all claims fully restore authored ground');
console.log('PASS ground departure hold: retirement, landing, retarget, sibling ownership, restoration');
