#!/usr/bin/env node
// Preserve native ESM and import.meta URLs in an immutable, retained release tree.
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, readdirSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, resolve, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'espree';

const ENTRIES = ['main.js', 'organism/hero-spores.js', 'organism/hero-spores-worker.js', 'hero-deco.js'];
const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');

export function runtimeBootstrap(base) {
  return `// Generated by tools/build-runtime-release.mjs; retain every runtime release.\n` +
    `(() => {\n` +
    `  const base = ${JSON.stringify(base)};\n` +
    `  window.__runtimeBase = base;\n` +
    `  const map = document.createElement('script');\n` +
    `  map.type = 'importmap';\n` +
    `  map.textContent = JSON.stringify({ imports: {\n` +
    `    './main.js': base + 'main.js',\n` +
    `    './organism/hero-spores.js': base + 'organism/hero-spores.js',\n` +
    `    'three': base + 'vendor/three/three.module.js',\n` +
    `    'three/addons/': base + 'vendor/three/addons/',\n` +
    `  } });\n` +
    `  document.head.appendChild(map);\n` +
    `})();\n`;
}

function walkAst(node, visit) {
  if (!node || typeof node !== 'object') return;
  visit(node);
  for (const value of Object.values(node)) {
    if (Array.isArray(value)) value.forEach(item => walkAst(item, visit));
    else if (value && typeof value === 'object') walkAst(value, visit);
  }
}

export function collectRuntime(root) {
  const files = new Map();
  function add(path) {
    const full = resolve(root, path);
    const key = relative(root, full).split(sep).join('/');
    if (key.startsWith('../') || key === '..') throw new Error(`Runtime path escapes source: ${path}`);
    if (files.has(key)) return;
    const bytes = readFileSync(full);
    files.set(key, bytes);
    if (!key.endsWith('.js')) return;
    const ast = parse(bytes.toString('utf8'), { ecmaVersion: 'latest', sourceType: 'module' });
    walkAst(ast, node => {
      let specifier;
      if (['ImportDeclaration', 'ExportNamedDeclaration', 'ExportAllDeclaration'].includes(node.type)) {
        specifier = node.source?.value;
      } else if (node.type === 'ImportExpression') {
        if (node.source.type !== 'Literal') throw new Error(`Nonliteral runtime import in ${key}`);
        specifier = node.source.value;
      }
      if (typeof specifier !== 'string') return;
      if (specifier === 'three') add('vendor/three/three.module.js');
      else if (specifier.startsWith('three/addons/')) add(`vendor/three/addons/${specifier.slice(13)}`);
      else if (specifier.startsWith('.')) {
        if (/[?#]/.test(specifier)) throw new Error(`Versioned source specifier in ${key}: ${specifier}`);
        add(relative(root, resolve(dirname(full), specifier)));
      } else throw new Error(`Unmapped runtime import in ${key}: ${specifier}`);
    });
  }
  ENTRIES.forEach(add);
  // These resources use import.meta-relative URLs, not ESM imports.
  add('assets/contributor-portraits/profile-sprite.jpg');
  add('static/geom/manifest.json');
  const manifest = JSON.parse(files.get('static/geom/manifest.json'));
  for (const chapter of Object.values(manifest.chapters)) add(`static/geom/${chapter.file}`);
  return new Map([...files].sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0));
}

function releaseHash(files) {
  const hash = createHash('sha256');
  for (const [path, bytes] of files) hash.update(path).update('\0').update(sha256(bytes)).update('\n');
  return hash.digest('hex');
}

export function verifyRetainedReleases(root) {
  const directory = resolve(root, 'runtime');
  if (!existsSync(directory)) throw new Error('No runtime release; run npm run runtime:build');
  for (const name of readdirSync(directory)) {
    if (!/^[a-f0-9]{64}$/.test(name)) throw new Error(`Unexpected runtime release path: ${name}`);
    const manifest = JSON.parse(readFileSync(resolve(directory, name, 'manifest.json'), 'utf8'));
    if (manifest.version !== 1 || manifest.hash !== name) throw new Error(`Invalid runtime manifest: ${name}`);
    const files = new Map();
    for (const entry of manifest.files) {
      if (entry.path.startsWith('/') || entry.path.split('/').includes('..')) throw new Error('Unsafe runtime manifest path');
      const bytes = readFileSync(resolve(directory, name, entry.path));
      if (sha256(bytes) !== entry.sha256) throw new Error(`Modified immutable runtime: ${name}/${entry.path}`);
      files.set(entry.path, bytes);
    }
    if (releaseHash(files) !== name) throw new Error(`Runtime release hash mismatch: ${name}`);
  }
}

export function buildRuntimeRelease({ root, check = false }) {
  const files = collectRuntime(root);
  const hash = releaseHash(files);
  const base = `./runtime/${hash}/`;
  const bootstrap = runtimeBootstrap(base);
  const destination = resolve(root, 'runtime', hash);
  if (check) {
    verifyRetainedReleases(root);
    if (!existsSync(destination) || readFileSync(resolve(root, 'runtime-release.js'), 'utf8') !== bootstrap) {
      throw new Error('Runtime release is stale; run npm run runtime:build and stage its output');
    }
  } else {
    if (existsSync(resolve(root, 'runtime'))) verifyRetainedReleases(root);
    if (!existsSync(destination)) {
      mkdirSync(resolve(root, 'runtime'), { recursive: true });
      const temporary = resolve(root, 'runtime', `.pending-${process.pid}`);
      try {
        mkdirSync(temporary);
        for (const [path, bytes] of files) {
          const target = resolve(temporary, path);
          mkdirSync(dirname(target), { recursive: true });
          writeFileSync(target, bytes);
        }
        writeFileSync(resolve(temporary, 'manifest.json'), JSON.stringify({
          version: 1, hash, entries: ENTRIES,
          files: [...files].map(([path, bytes]) => ({ path, sha256: sha256(bytes) })),
        }, null, 2) + '\n');
        renameSync(temporary, destination);
      } finally { rmSync(temporary, { recursive: true, force: true }); }
    }
    const temporary = resolve(root, `.runtime-release-${process.pid}.tmp`);
    writeFileSync(temporary, bootstrap);
    renameSync(temporary, resolve(root, 'runtime-release.js'));
  }
  return { hash, base, files: files.size, bytes: [...files.values()].reduce((sum, bytes) => sum + bytes.length, 0) };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const rootIndex = args.indexOf('--root');
  if (rootIndex !== -1 && (!args[rootIndex + 1] || args[rootIndex + 1].startsWith('--'))) {
    throw new Error('--root requires a directory');
  }
  const root = rootIndex === -1 ? resolve(dirname(fileURLToPath(import.meta.url)), '..') : resolve(args[rootIndex + 1]);
  if (args.some((arg, index) => arg !== '--check' && arg !== '--root' && !(rootIndex !== -1 && index === rootIndex + 1))) {
    throw new Error('Usage: node tools/build-runtime-release.mjs [--check] [--root PATH]');
  }
  console.log(`runtime release ${args.includes('--check') ? 'verified' : 'built'}: ${JSON.stringify(buildRuntimeRelease({ root, check: args.includes('--check') }))}`);
}
